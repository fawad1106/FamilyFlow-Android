@app.post("/api/auth/register")
def register(x:Cred,response:Response):
    name=x.username.strip().lower()
    try:
        with engine.begin() as db:
            r=db.execute(text("INSERT INTO users(username,password_hash,email) VALUES(:n,:p,:e) RETURNING id"),{"n":name,"p":phash(x.password),"e":(x.email or "").strip().lower() or None}).first()
            uid=r[0]
    except IntegrityError: raise HTTPException(409,"Username already exists.")
    response.set_cookie("lifeos_session",session(uid),httponly=True,samesite="lax",secure=url.startswith("postgres"),max_age=2592000)
