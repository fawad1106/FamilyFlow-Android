def send_email(to, subject, body):
    host=os.getenv("SMTP_HOST")
    if not host or not to: return False
    msg=EmailMessage(); msg["From"]=os.getenv("SMTP_FROM",os.getenv("SMTP_USER","LifeOS")); msg["To"]=to; msg["Subject"]=subject; msg.set_content(body)
    with smtplib.SMTP(host,int(os.getenv("SMTP_PORT","587")),timeout=20) as s:
        if os.getenv("SMTP_TLS","1")=="1": s.starttls()
        if os.getenv("SMTP_USER"): s.login(os.getenv("SMTP_USER"),os.getenv("SMTP_PASSWORD",""))
        s.send_message(msg)
    return True

