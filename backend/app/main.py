def phash(p):
    salt=secrets.token_bytes(16); key=hashlib.scrypt(p.encode(),salt=salt,n=16384,r=8,p=1)
    return base64.b64encode(salt+b"."+key).decode()
def pcheck(p,s):
    try:
        raw=base64.b64decode(s); salt,key=raw.split(b".",1)
        return hmac.compare_digest(key,hashlib.scrypt(p.encode(),salt=salt,n=16384,r=8,p=1))
    except Exception:return False
def tags(s): return ",".join(dict.fromkeys(x.strip() for x in (s or "").split(",") if x.strip()))
def session(uid):
    token=secrets.token_urlsafe(48)
    with engine.begin() as db: db.execute(text("INSERT INTO sessions(token,user_id) VALUES(:t,:u)"),{"t":token,"u":uid})
    return token
def user(cookie):
    if not cookie:return None
    with engine.connect() as db:return db.execute(text("SELECT u.id,u.username,u.created_at FROM users u JOIN sessions s ON s.user_id=u.id WHERE s.token=:t"),{"t":cookie}).mappings().first()
def need(cookie):
    u=user(cookie)
    if not u:raise HTTPException(401,"Please log in.")
    return u
